def build():
    out = []
    for p in PLACES:
        c = COORDS.get(p["name"])
        if c:
            p["lon"], p["lat"] = c
        out.append(p)
    return out


if __name__ == "__main__":
    import argparse
    # 先把参数解析掉：--help 不该先跑一遍 build() 再打印用法
    ap = argparse.ArgumentParser(
        description="多片区景点池构建（改 COORDS / REGIONS / PLACES 换目的地）")
    ap.add_argument("--out", default="places.json", help="输出路径")
    ap.add_argument("--quiet", action="store_true", help="只输出一行结果")
    args = ap.parse_args()

    places = build()
    located = sum(1 for p in places if "lon" in p)
    if not args.quiet:
        print(f"景点池 {len(places)} 个，已定位 {located} 个")
        for q in places:
            if "lon" not in q:
                print(f"  [未定位] {q['name']}")
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        json.dump(places, f, ensure_ascii=False, indent=2)
    print(f"→ {args.out}（{located}/{len(places)} 已定位）")
