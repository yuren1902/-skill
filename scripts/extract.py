def looks_like_place(name):
    """严格判定：必须是干净的地名，不能是句子碎片"""
    if len(name) < 2 or len(name) > 14:
        return False
    if is_excluded(name):
        return False
    # 必须以后缀结尾（而非仅包含），避免"除了魯迅故里和沈園"这类碎片
    return any(name.endswith(suf) for suf in PLACE_SUFFIX)


def extract_from_graded(graded):
    """从检索结果中提取地点候选"""
    candidates = {}

    # 1) 白名单优先（质量最可靠）
    for name, (t, price, dur, note) in KNOWN_SPOTS.items():
        candidates[name] = {
            "name": name, "type": t,
            "ticket_price": price, "duration_min": dur,
            "note": note, "address": "绍兴市越城区" if t != "T" else "绍兴市",
            "reservation_required": name in ("鲁迅故里", "大禹陵", "兰亭", "绍兴博物馆新馆", "绍兴美术馆"),
            "reservation_tips": "建议提前在官方公众号预约" if name in ("鲁迅故里", "大禹陵") else "",
            "src_file": "whitelist", "confidence": "high",
        }

    # 2) 从文本中补充（标题/摘要里出现的地点）
    for item in graded:
        if item.get("grade") == "D":
            continue
        blob = f"{item.get('title','')} {item.get('summary','')}"
        for raw_token in re.findall(r"[\u4e00-\u9fa5]{2,14}", blob):
            token = to_simplified(raw_token)          # 繁 → 简
            token = NAME_ALIAS.get(token, token)      # 别名归一
            if token in NON_PLACE_WORDS:
                continue
            if not looks_like_place(token):
                continue
            if token in candidates:
                continue
            # 净化：若该 token 已被白名单中某地点名包含（或其包含白名单名），
            # 视为同一地点的变体，不再重复收录
            if any(wl in token or token in wl for wl in KNOWN_SPOTS):
                continue
            # 更严格：必须是干净的地名（长度 ≤8 且不含数量词/动词前缀）
            if len(token) > 8:
                continue
            if re.search(r"(涵盖|紧邻|新增|按|选|包括|位于|推荐|高铁|至)", token):
                continue
            candidates[token] = {
                "name": token, "type": classify_supplement(token),
                "ticket_price": None, "duration_min": 90,
                "note": (item.get("summary") or "")[:200],
                "address": "绍兴市",
                "reservation_required": "预约" in blob,
                "reservation_tips": "", "src_file": item.get("query_key", ""),
                "confidence": "medium",
            }
    return list(candidates.values())


def classify_supplement(name):
    """补充地点的类型判定"""
    if any(k in name for k in ["站", "地铁"]):
        return "T"
    if any(k in name for k in ["古镇", "古街", "街", "水街"]):
        return "F"
    if any(k in name for k in ["馆", "故居", "书屋"]):
        return "U"
    return "5"


def main():
    p = argparse.ArgumentParser(description="地点提取（规则引擎）")
    p.add_argument("--graded", required=True)
    p.add_argument("--out", required=True)
    args = p.parse_args()

    graded = json.load(open(args.graded, encoding="utf-8"))
    places = extract_from_graded(graded)

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    json.dump(places, open(args.out, "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)

    high = sum(1 for x in places if x["confidence"] == "high")
    print(f"提取地点 {len(places)} 个（高置信 {high} / 中置信 {len(places)-high}）→ {args.out}",
          file=sys.stderr)
    for x in places:
        print(f"  [{x['type']}] {x['name']}  ({x['confidence']})", file=sys.stderr)


if __name__ == "__main__":
    main()
